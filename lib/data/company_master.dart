class CompanyMasterEntry {
  const CompanyMasterEntry({
    required this.companyId,
    required this.companyName,
    required this.ticker,
    required this.industry,
    required this.isNikkei225,
  });

  final String companyId;
  final String companyName;
  final String ticker;
  final String industry;
  final bool isNikkei225;

  String get artworkPath => 'assets/company_art/$companyId.png';
}

abstract final class CompanyMaster {
  static const List<CompanyMasterEntry> nikkei225Companies =
      _nikkei225Companies;

  /// All companies known to KABUCA, including cards retained for compatibility.
