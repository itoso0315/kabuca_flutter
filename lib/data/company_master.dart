    CompanyMasterEntry(
      companyId: 'saizeriya',
      companyName: 'サイゼリヤ',
      ticker: '7581',
      industry: '外食',
      isNikkei225: false,
    ),
  ];

  static final Map<String, CompanyMasterEntry> _byId =
      <String, CompanyMasterEntry>{
        for (final company in companies) company.companyId: company,
      };
