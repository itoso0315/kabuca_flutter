      <String, CompanyMasterEntry>{
        for (final company in companies) company.ticker: company,
      };

  static CompanyMasterEntry? byId(String companyId) => _byId[companyId];
  static CompanyMasterEntry? byTicker(String ticker) => _byTicker[ticker];
}

